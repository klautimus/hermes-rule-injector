"""Rule definitions and storage for the rule-injector plugin.

Rules are stored in rules.json alongside this plugin. The RuleStore handles
atomic reads/writes with hot-reload via mtime checking.
"""

import json
import logging
import os
import time
import uuid
from dataclasses import dataclass, asdict, field
from typing import List, Optional

RULES_FILE = os.path.join(os.path.dirname(__file__), "rules.json")

# Recognized trigger options for validation. Update this set when adding new
# options to matchers.py. Catches typos like `exclude_if_crno` (which the cron
# audit 2026-07-21 found in manage-confusion description vs trigger dict).
_KNOWN_TRIGGER_OPTIONS = {
    # trigger types
    "type",
    # scopes
    "scope",
    # keyword / pattern matching
    "keywords",
    "patterns",
    "case_insensitive",
    "match_all",
    # tool matching
    "tool_names",
    # result conditions
    "result_truncated",
    "empty_result",
    "result_contains_keywords",
    # semantic
    "references",
    "threshold",
    # state
    "min_attempts",
    "post_compaction",
    # compound
    "conditions",
    "operator",
    # exclusions
    "exclude_if_skill_loaded",
    "exclude_if_cron",
    "exclude_if_recent_context_keywords",
    "cooldown_turns",
    "max_fires_per_session",
    # meta-discussion suppression (D11 fix 2026-07-21)
    "suppress_on_meta_discussion",
    # Active tool/skill compliance controls
    "required_tools",
    "required_skills",
    "match_all_tools",
}

_KNOWN_INJECT_OPTIONS = {"context", "result_suffix", "message"}

_KNOWN_RULE_OPTIONS = {
    "id", "name", "description", "enabled", "hook", "priority",
    "trigger", "inject", "created_at", "updated_at",
    # Plan 007: domain/applicability schema (new in v1.1).
    "domain", "applicable_when", "not_applicable_when", "safety_critical",
    # Auto-creation provenance (added 2026-08-08): when the background-review
    # fork drafts a rule from an observed correction and the adjudicator
    # approves it, these fields mark it as auto-created so users can audit,
    # review, or remove auto-generated rules via the CLI/dashboard without
    # affecting hand-curated rules.
    "auto_created", "auto_created_source", "auto_created_at",
}

# Maximum auto-created rules allowed before the oldest is auto-archived.
# Prevents rules.json from bloating unbounded across sessions. Set high
# enough that real, recurring corrections all stick; low enough that one
# noisy session can't push hand-curated rules out of budget.
MAX_AUTO_CREATED_RULES = 50


@dataclass
class Rule:
    """A single injection rule."""
    id: str
    name: str
    description: str = ""
    enabled: bool = True
    hook: str = "pre_llm_call"  # pre_llm_call | transform_tool_result | pre_verify
    priority: int = 10  # lower = higher priority
    trigger: dict = field(default_factory=dict)
    inject: dict = field(default_factory=dict)  # {"context": "..."} or {"result_suffix": "..."} or {"message": "..."}
    created_at: str = ""
    updated_at: str = ""
    # F7 (2026-08-04 audit): Plan 007 metadata — validated as KNOWN top-level
    # options but previously silently DROPPED at load. The adjudicator payload
    # hard-coded safety_critical=False, so the safety floor could never engage.
    domain: str = ""
    applicable_when: list = field(default_factory=list)
    not_applicable_when: list = field(default_factory=list)
    safety_critical: bool = False
    # Auto-creation provenance (added 2026-08-08). When auto_created=True,
    # the rule was generated by the background-review fork from an observed
    # user correction and approved by the Adjudicator. auto_created_source
    # records what triggered the draft (e.g. "oob_message", "stop_event",
    # "explicit_correction"). auto_created_at is the ISO-8601 timestamp of
    # creation. All three fields are added by the tool; hand-curated rules
    # have them absent or False.
    auto_created: bool = False
    auto_created_source: str = ""
    auto_created_at: str = ""

    def to_dict(self) -> dict:
        return asdict(self)


class RuleStore:
    """Atomic JSON-backed rule store with hot-reload."""

    def __init__(self, path: str = RULES_FILE):
        self.path = path
        self._cache: Optional[list] = None
        self._mtime: float = 0

    def _check_reload(self):
        """Hot-reload when file changes (dashboard writes trigger this)."""
        try:
            mtime = os.path.getmtime(self.path) if os.path.exists(self.path) else 0
        except OSError:
            mtime = 0
        if mtime != self._mtime:
            self._cache = None
            self._mtime = mtime

    def load(self) -> list:
        """Load all rules. Returns list of Rule objects."""
        self._check_reload()
        if self._cache is not None:
            return self._cache

        if not os.path.exists(self.path):
            self._cache = []
            return self._cache

        try:
            with open(self.path, "r") as f:
                data = json.load(f)
        except (json.JSONDecodeError, OSError):
            self._cache = []
            return self._cache

        rules = []
        logger = logging.getLogger(__name__)
        for r in data.get("rules", []):
            try:
                # Validate top-level keys BEFORE dataclass conversion. Catches
                # typos like the manage-confusion issue where exclude_if_cron
                # was set in description but not in trigger dict.
                unknown_top = set(r.keys()) - _KNOWN_RULE_OPTIONS
                if unknown_top:
                    logger.warning(
                        "rule-injector: rule '%r' has unrecognized top-level options: %s. "
                        "Known options: %s",
                        r.get("id", "<unnamed>"), sorted(unknown_top), sorted(_KNOWN_RULE_OPTIONS)
                    )
                rules.append(Rule(
                    id=r.get("id", str(uuid.uuid4())),
                    name=r.get("name", "Unnamed"),
                    description=r.get("description", ""),
                    enabled=r.get("enabled", True),
                    hook=r.get("hook", "pre_llm_call"),
                    priority=r.get("priority", 10),
                    trigger=r.get("trigger", {}),
                    inject=r.get("inject", {}),
                    created_at=r.get("created_at", ""),
                    updated_at=r.get("updated_at", ""),
                    domain=r.get("domain", ""),
                    applicable_when=r.get("applicable_when", []) or [],
                    not_applicable_when=r.get("not_applicable_when", []) or [],
                    safety_critical=bool(r.get("safety_critical", False)),
                    auto_created=bool(r.get("auto_created", False)),
                    auto_created_source=str(r.get("auto_created_source", "")),
                    auto_created_at=str(r.get("auto_created_at", "")),
                ))
            except Exception:
                continue  # skip invalid rule

        # Validate trigger / inject options to catch typos like the
        # exclude_if_cron issue found in cron audit 2026-07-21.
        # Logs warnings (does not raise) — backwards-compatible with rules
        # that may have historical unknowns.
        logger = logging.getLogger(__name__)
        for rule in rules:
            unknown = set(rule.trigger.keys()) - _KNOWN_TRIGGER_OPTIONS
            if unknown:
                logger.warning(
                    "rule-injector: rule '%s' has unrecognized trigger options: %s. "
                    "Known options: %s",
                    rule.id, sorted(unknown), sorted(_KNOWN_TRIGGER_OPTIONS)
                )
            unknown_inject = set(rule.inject.keys()) - _KNOWN_INJECT_OPTIONS
            if unknown_inject:
                logger.warning(
                    "rule-injector: rule '%s' has unrecognized inject options: %s. "
                    "Known options: %s",
                    rule.id, sorted(unknown_inject), sorted(_KNOWN_INJECT_OPTIONS)
                )
            # Note: cannot validate top-level rule keys against _KNOWN_RULE_OPTIONS
            # here because Rule is a dataclass (not a dict). Validation of top-level
            # keys would require inspecting the original JSON dict in data["rules"]
            # before constructing the dataclass. Skipped for now — typos at the
            # top level are caught at JSON parse time when the dataclass constructor
            # raises.

        self._cache = rules
        return rules

    def save(self, rules: list):
        """Atomic write (temp file + rename)."""
        data = {
            "version": 1,
            "rules": [r.to_dict() if isinstance(r, Rule) else r for r in rules]
        }
        os.makedirs(os.path.dirname(self.path), exist_ok=True)
        tmp = self.path + ".tmp"
        with open(tmp, "w") as f:
            json.dump(data, f, indent=2)
        os.rename(tmp, self.path)
        self._mtime = os.path.getmtime(self.path)
        self._cache = rules

    def add(self, rule_data: dict) -> Rule:
        """Create a new rule. Returns the created Rule.

        If the rule has auto_created=True and the auto-created rule count
        exceeds MAX_AUTO_CREATED_RULES, the OLDEST auto-created rules are
        evicted (FIFO) so a noisy session cannot push hand-curated rules
        out of budget or cause unbounded growth of rules.json. Hand-curated
        rules (auto_created=False) are NEVER evicted.
        """
        now = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
        is_auto = bool(rule_data.get("auto_created", False))
        rule = Rule(
            id=rule_data.get("id") or str(uuid.uuid4())[:8],
            name=rule_data.get("name", "Unnamed Rule"),
            description=rule_data.get("description", ""),
            enabled=rule_data.get("enabled", True),
            hook=rule_data.get("hook", "pre_llm_call"),
            priority=rule_data.get("priority", 10),
            trigger=rule_data.get("trigger", {}),
            inject=rule_data.get("inject", {}),
            created_at=rule_data.get("created_at") or now,
            updated_at=now,
            domain=rule_data.get("domain", ""),
            applicable_when=rule_data.get("applicable_when", []) or [],
            not_applicable_when=rule_data.get("not_applicable_when", []) or [],
            safety_critical=bool(rule_data.get("safety_critical", False)),
            auto_created=is_auto,
            auto_created_source=rule_data.get("auto_created_source", ""),
            auto_created_at=rule_data.get("auto_created_at") or now,
        )
        rules = self.load()
        # Auto-creation eviction (FIFO, oldest first). Only applies when the
        # incoming rule is itself auto-created; a hand-curated rule is always
        # appended regardless of the auto-count, because the hand-curator owns
        # the file.
        if is_auto:
            auto_rules = [r for r in rules if r.auto_created]
            # Sort by auto_created_at ascending — oldest first.
            auto_rules.sort(key=lambda r: r.auto_created_at or "")
            excess = len(auto_rules) + 1 - MAX_AUTO_CREATED_RULES
            if excess > 0:
                to_evict = auto_rules[:excess]
                evict_ids = {r.id for r in to_evict}
                rules = [r for r in rules if r.id not in evict_ids]
        rules.append(rule)
        self.save(rules)
        return rule

    def update(self, rule_id: str, updates: dict) -> Optional[Rule]:
        """Update an existing rule. Returns the updated Rule or None."""
        rules = self.load()
        for r in rules:
            if r.id == rule_id:
                if "name" in updates:
                    r.name = updates["name"]
                if "description" in updates:
                    r.description = updates["description"]
                if "enabled" in updates:
                    r.enabled = updates["enabled"]
                if "hook" in updates:
                    r.hook = updates["hook"]
                if "priority" in updates:
                    r.priority = updates["priority"]
                if "trigger" in updates:
                    r.trigger = updates["trigger"]
                if "inject" in updates:
                    r.inject = updates["inject"]
                if "domain" in updates:
                    r.domain = updates["domain"]
                if "applicable_when" in updates:
                    r.applicable_when = updates["applicable_when"] or []
                if "not_applicable_when" in updates:
                    r.not_applicable_when = updates["not_applicable_when"] or []
                if "safety_critical" in updates:
                    r.safety_critical = bool(updates["safety_critical"])
                if "auto_created" in updates:
                    r.auto_created = bool(updates["auto_created"])
                if "auto_created_source" in updates:
                    r.auto_created_source = str(updates["auto_created_source"])
                if "auto_created_at" in updates:
                    r.auto_created_at = str(updates["auto_created_at"])
                r.updated_at = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
                self.save(rules)
                return r
        return None

    def delete(self, rule_id: str) -> bool:
        """Delete a rule. Returns True if deleted, False if not found."""
        rules = self.load()
        original = len(rules)
        rules = [r for r in rules if r.id != rule_id]
        if len(rules) < original:
            self.save(rules)
            return True
        return False

    def toggle(self, rule_id: str) -> Optional[Rule]:
        """Toggle a rule's enabled state without deleting it."""
        rules = self.load()
        for r in rules:
            if r.id == rule_id:
                r.enabled = not r.enabled
                r.updated_at = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
                self.save(rules)
                return r
        return None

    def get(self, rule_id: str) -> Optional[Rule]:
        """Get a single rule by ID."""
        for r in self.load():
            if r.id == rule_id:
                return r
        return None

    def list_auto(self) -> List[Rule]:
        """Return all auto-created rules, ordered by auto_created_at ascending.

        Used by the CLI (`hermes rule-injector list-auto`) and the dashboard
        so users can audit, review, or remove auto-generated rules without
        affecting hand-curated rules. Sort order matches the eviction order
        (oldest first) so the CLI output and the eviction policy agree.
        """
        rules = [r for r in self.load() if r.auto_created]
        rules.sort(key=lambda r: r.auto_created_at or "")
        return rules

    def count_auto(self) -> int:
        """Return the number of auto-created rules currently in the store."""
        return sum(1 for r in self.load() if r.auto_created)

    def remove_all_auto(self) -> int:
        """Remove every auto-created rule. Returns the number of rules removed.

        Used by the CLI `hermes rule-injector remove-all-auto` command and
        the dashboard "clear auto-created rules" action. Hand-curated rules
        are NEVER touched. The atomic save() rebuilds the file with the
        trimmed list.
        """
        rules = self.load()
        kept = [r for r in rules if not r.auto_created]
        removed = len(rules) - len(kept)
        if removed > 0:
            self.save(kept)
        return removed
